// 叙事约束（可在「插件」设置页独立开关）：
// - buildNarrativeGuard：叙事防护——外部世界参与、角色入场节制、主角为中心（防男女主二人转/角色过载）
// - buildProgressionGuard：剧情推进——每段推进剧情、防原地打转、结尾留钩（防外部停滞）

export function buildNarrativeGuard(): string {
  return `【叙事护栏·必须严格遵守】
1. 世界是活的：剧情必须有外部世界参与。视剧情需要引入或延续其他 NPC、势力与环境事件（路人、随从、同门、对手、告示、来信、天灾、异动、第三方冲突等）；严禁全篇只有男女主角两个人对话互动（"二人转"），严禁外部世界永远静止。
2. 角色管理（防止角色过载）：
   - 优先复用：优先延续并深化已出场角色的互动与关系，而不是频繁介绍新人；
   - 入场节制：每段回复最多引入 1 个新角色；新角色必须有明确戏份目的，否则用无名龙套（店家、路人等）一带而过、用完即退场；
   - 同屏上限：同时活跃的主要角色不超过 3-4 个，其余角色背景化处理，不逐一点名；
   - 出场即锚定：新角色入场时一次交代可记忆的身份/称谓/一个特征，不堆砌名字让读者疲于辨认。
3. 主角为中心：主角（用户角色）是叙事中心与视角锚点；男女主之间即便有感情线，也必须穿插外部角色与事件的参与，推动关系与剧情发展。`;
}

export function buildProgressionGuard(): string {
  return `【剧情推进·必须严格遵守】
1. 每段回复必须推进至少一个剧情要素：新事件、新信息、冲突升级、关系变化、场景转移、情感转折或新角色入场。
2. 严禁原地打转：不重复已写过的场景、对话与心理描写；剧情不得在两人之间循环拉扯而无实质进展；不得用"接下来怎么办"式的空泛收尾敷衍。
3. 结尾留钩：结尾留下一处具体可继续的行动、选择或悬念，便于玩家接续。`;
}
